#!/bin/bash
# Usage: build.sh APP LIB [PROFILE] [N]
#   APP      a directory under apps/ (todomvc, jsfb, life, synthetic, ...)
#   LIB      yew (yew 0.23 from crates.io) | leafy (../leafy, under yew's
#            name)
#   PROFILE  speed (optimized for speed: opt-level 3, codegen-units 1, no
#            LTO; wasm-opt -O4) | size (optimized for size: opt-level "z",
#            codegen-units 1, fat LTO, panic = "abort"; wasm-opt -Oz)
#   N        synthetic only: number of generated components (default 200)
#
# Generates a crate for the variant in out/APP[-N]-LIB-PROFILE/ (Cargo.toml
# whose binary is apps/APP/src/main.rs, and index.html), builds it with
# trunk (release, build-std, then wasm-opt; see .cargo/config.toml and
# rust-toolchain.toml), strips all custom sections and prints raw and
# brotli (-q $BROTLI, by default 11) sizes. The site is in out/.../dist. Variants with the same
# LIB and PROFILE share a target directory (out/target-LIB-PROFILE).
set -euo pipefail
cd "$(dirname "$0")"
usage() { sed -n '2,10p' "$0" >&2; exit 1; }
APP=${1:-}; LIB=${2:-}; PROFILE=${3:-speed}; N=${4:-200}
[ -n "$APP" ] && [ -f "apps/$APP/deps.toml" ] || usage
case $PROFILE in
    speed) PROF=$'opt-level = 3\ncodegen-units = 1\nlto = false'; WASM_OPT=4 ;;
    size) PROF=$'opt-level = "z"\ncodegen-units = 1\nlto = true\npanic = "abort"'; WASM_OPT=z ;;
    *) usage ;;
esac
case $LIB in
    yew) YEW='yew = { version = "0.23", features = ["csr"] }' ;;
    leafy) YEW='yew = { package = "leafy", path = "../../../leafy" }' ;;
    *) usage ;;
esac

NAME=$APP
[ "$APP" = synthetic ] && NAME=$APP-$N
OUT=out/$NAME-$LIB-$PROFILE
mkdir -p "$OUT"
BIN=../../apps/$APP/src/main.rs
if [ "$APP" = synthetic ]; then
    # A copy of its own, so variants can be built at the same time.
    mkdir -p "$OUT/src"
    cp apps/synthetic/src/main.rs "$OUT/src/main.rs"
    python3 apps/synthetic/gen.py "$N" > "$OUT/src/generated.rs"
    BIN=src/main.rs
fi
cat > "$OUT/Cargo.toml" <<EOF
# Generated by bench/build.sh.
[package]
name = "bench-$APP"
version = "0.0.0"
edition = "2021"
authors = ["Claude Code", "Finn Bear"]
publish = false

[[bin]]
name = "app"
path = "$BIN"

[dependencies]
$YEW
$(cat "apps/$APP/deps.toml")

[profile.release]
$PROF

[workspace]
EOF
LINK="<link data-trunk rel=\"rust\" data-bin=\"app\" data-wasm-opt=\"$WASM_OPT\" data-wasm-opt-params=\"--debuginfo\" data-keep-debug/>"
sed "s|TRUNK_LINK|$LINK|" "apps/$APP/index.html" > "$OUT/index.html"
# apps/APP/Cargo.lock pins dependency versions: the yew build updates it, and
# it seeds the leafy build so that the dependencies both use are the same.
[ -f "apps/$APP/Cargo.lock" ] && cp "apps/$APP/Cargo.lock" "$OUT/Cargo.lock"

# (With $SLOT, one of its own, for builds at the same time; see
# buildtime.sh.)
export CARGO_TARGET_DIR=$PWD/out/target-$LIB-$PROFILE${SLOT:+-slot$SLOT}
(cd "$OUT" && trunk build --release --no-sri --skip-version-check --filehash false --dist dist > build.log 2>&1) \
    || { tail -50 "$OUT/build.log"; exit 1; }
[ "$LIB" = yew ] && [ -z "${SLOT:-}" ] && cp "$OUT/Cargo.lock" "apps/$APP/Cargo.lock"

wasm-tools strip --all "$OUT/dist/app_bg.wasm" -o "$OUT/stripped.wasm"
BROTLI=${BROTLI:-11}
brotli -q "$BROTLI" -f -o "$OUT/stripped.wasm.br" "$OUT/stripped.wasm"
brotli -q "$BROTLI" -f -o "$OUT/app.js.br" "$OUT/dist/app.js"
SIZES="wasm=$(stat -c %s "$OUT/stripped.wasm") wasm.br=$(stat -c %s "$OUT/stripped.wasm.br") js.br=$(stat -c %s "$OUT/app.js.br")"
echo "$SIZES" > "$OUT/sizes.txt"
printf "%-14s %-5s %-8s %s\n" "$NAME" "$LIB" "$PROFILE" "$SIZES"
