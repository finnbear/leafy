#!/bin/bash
# Usage: ssr.sh [SAMPLES=30]
# Builds the server-rendering benchmark (apps/ssr, with apps/synthetic's
# generator's 100 components) natively, against yew 0.23 and against leafy,
# runs each (pinned to one core), and writes the median time per render of
# each scene to out/ssr.json. Plot with ssr.mjs.
set -euo pipefail
cd "$(dirname "$0")"
SAMPLES=${1:-30}
HERE=$PWD
results="{"
for lib in yew leafy; do
    OUT=out/ssr-$lib
    mkdir -p "$OUT/src"
    cp apps/ssr/src/main.rs "$OUT/src/main.rs"
    python3 apps/synthetic/gen.py 100 > "$OUT/src/generated.rs"
    if [ "$lib" = yew ]; then
        DEP='yew = { version = "0.23", features = ["ssr"] }'; FEATURES=
    else
        DEP='yew = { package = "leafy", path = "../../../leafy" }'; FEATURES="--features leafy"
    fi
    cat > "$OUT/Cargo.toml" <<TOML
# Generated by bench/ssr.sh.
[package]
name = "bench-ssr"
version = "0.0.0"
edition = "2021"
authors = ["Claude Code", "Finn Bear"]
publish = false

[[bin]]
name = "app"
path = "src/main.rs"

[features]
leafy = []

[dependencies]
$DEP
web-sys = { version = "0.3", features = ["HtmlInputElement", "InputEvent", "KeyboardEvent", "MouseEvent", "Window", "console"] }
wasm-bindgen = "0.2"

[profile.release]
opt-level = 3
codegen-units = 1

[workspace]
TOML
    # Natively, with the default toolchain: from outside bench/ (whose
    # config and toolchain are for wasm).
    (cd / && cargo build --release --quiet --manifest-path "$HERE/$OUT/Cargo.toml" $FEATURES)
    json=$(cd / && taskset -c 0 "$HERE/$OUT/target/release/app" "$SAMPLES")
    echo "$lib: $json"
    results+="\"$lib\": $json,"
done
echo "${results%,}}" > out/ssr.json
echo out/ssr.json
